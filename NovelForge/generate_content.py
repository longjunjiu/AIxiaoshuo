    def ask_choice(self, question: str, options: dict, allow_multiple: bool = False) -> any:
        self.print_header(question)
        for key, option in options.items():
            print(f"\n  【{key}】{option['name']}")
            print(f"  {option.get('description', '')}")
            if "方案" in option:
                for i, plan in enumerate(option["方案"], 1):
                    print(f"    {i}. {plan}")
            if "参考" in option:
                print(f"  参考: {', '.join(option['参考'])}")

        if allow_multiple:
            print("\n  💡 可选多个，用逗号分隔")
            while True:
                response = input("\n  请选择: ").strip()
                try:
                    choices = [x.strip() for x in response.split(",")]
                    if all(c in options for c in choices):
                        return choices
                except:
                    pass
        else:
            while True:
                response = input("\n  请选择: ").strip()
                if response in options:
                    return response
                print("  请输入有效选项")

    def ask_input(self, question: str, default: str = "") -> str:
        print(f"\n  {question}")
        if default:
            response = input(f"  (回车默认: {default}): ").strip()
        else:
            response = input("  请输入: ").strip()
        return response if response else default

    def ask_confirm(self, question: str, default: bool = True) -> bool:
        choice = "[Y/n]" if default else "[y/N]"
        while True:
            response = input(f"\n  {question} {choice}: ").strip().lower()
            if not response:
                return default
            if response in ("y", "yes"):
                return True
            if response in ("n", "no"):
                return False
            print("  请输入 y 或 n")

